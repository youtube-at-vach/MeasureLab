def apply_translations():
    for lang, mapping in translations.items():
        lang_path = os.path.join(LANG_DIR, f"{lang}.json")
        if not os.path.exists(lang_path):
            print(f"Error: {lang_path} not found.")
            continue
        
        with open(lang_path, "r", encoding="utf-8") as f:
            data = json.load(f)
            
        print(f"Applying translations to {lang}.json...")
        added_count = 0
        updated_count = 0
        
        for k, v in mapping.items():
            if k not in data:
                data[k] = v
                added_count += 1
            elif data[k] == k or data[k] == "":  # placeholder or empty
                data[k] = v
                updated_count += 1
            else:
                # Update if the current value is equal to the English value (placeholder)
                # Ensure we only overwrite placeholders, not custom translated ones
                # For non-English languages, if the value is exactly the English key, it's a placeholder
                if data[k] == k:
                    data[k] = v
                    updated_count += 1
                else:
                    # Force update Transmission Analyzer key since we want to override it with correct translations
                    data[k] = v
                    updated_count += 1

        # Sort the dictionary keys to guarantee deterministic output order
        sorted_data = dict(sorted(data.items()))
        
        with open(lang_path, "w", encoding="utf-8") as f:
            json.dump(sorted_data, f, ensure_ascii=False, indent=4)
            f.write("\n")
            
        print(f"  Done. Added: {added_count}, Updated: {updated_count}")

if __name__ == "__main__":
    apply_translations()
